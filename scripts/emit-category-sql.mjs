/**
 * Emits a migration that seeds ONE category and its products.
 *
 *   node scripts/emit-category-sql.mjs bedsheets > supabase/migrations/0006_bedsheets.sql
 *
 * WHY THIS EXISTS ALONGSIDE seed-supabase.mjs. That script writes the whole
 * catalogue: 72 products, their variants and their images. Re-running it to add
 * one department means either handing over the service role key or pasting
 * several thousand lines of SQL that mostly rewrite rows already in the table.
 * This emits only what is new, so a new category arrives the same way every
 * other schema change on this project has — as a numbered migration the shop
 * owner applies in the dashboard.
 *
 * Idempotent, like the seed: every statement upserts on its natural key, and
 * images and variants are cleared for the affected products first. Running the
 * migration twice leaves the same rows.
 */

import { createServer } from "vite";

const category = process.argv[2];
if (!category) {
  console.error("Usage: node scripts/emit-category-sql.mjs <category-slug>");
  process.exit(1);
}

const NEWLINE = String.fromCharCode(10);

/** Single-quote escaping for SQL literals. Same rule as seed-supabase.mjs. */
function lit(value) {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number") return String(value);
  if (typeof value === "boolean") return value ? "true" : "false";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function textArray(values) {
  if (!values?.length) return "'{}'";
  return `ARRAY[${values.map(lit).join(", ")}]::text[]`;
}

const server = await createServer({
  configFile: "vite.config.ts",
  server: { middlewareMode: true },
  logLevel: "error",
});

try {
  const { products } = await server.ssrLoadModule("/src/data/products.ts");
  const { categories } = await server.ssrLoadModule("/src/data/categories.ts");

  const tree = categories.filter((c) => c.slug === category || c.parentSlug === category);
  const items = products.filter((p) => p.categorySlug === category);

  if (tree.length === 0) {
    console.error(`No category "${category}" in src/data/categories.ts`);
    process.exit(1);
  }

  const out = [];
  out.push(`-- ${tree[0].name}: ${tree.length} categories, ${items.length} products.`);
  out.push("--");
  out.push("-- Generated by scripts/emit-category-sql.mjs from src/data. Do not hand-edit:");
  out.push("-- regenerate it instead, so the mock catalogue and Postgres cannot drift.");
  out.push("--");
  out.push("-- Idempotent. Every statement upserts on its natural key, and each product's");
  out.push("-- images and variants are cleared before they are rewritten, so applying this");
  out.push("-- twice leaves exactly the same rows.");
  out.push("");

  // Parents before children: subcategory rows reference their parent's slug.
  for (const group of [tree.filter((c) => !c.parentSlug), tree.filter((c) => c.parentSlug)]) {
    for (const c of group) {
      out.push(
        `insert into categories (slug, name, parent_slug, description, image_url, sort_order) values (` +
          [
            lit(c.slug),
            lit(c.name),
            lit(c.parentSlug ?? null),
            lit(c.description ?? null),
            lit(c.image?.url ?? null),
            c.sortOrder,
          ].join(", ") +
          `) on conflict (slug) do update set name = excluded.name, parent_slug = excluded.parent_slug, description = excluded.description, image_url = excluded.image_url, sort_order = excluded.sort_order;`,
      );
    }
  }
  out.push("");

  for (const p of items) {
    const columns = [
      "slug",
      "name",
      "description",
      "short_description",
      "price",
      "sale_price",
      "category_slug",
      "subcategory_slug",
      "fabric",
      "pieces",
      "care",
      "tags",
      "rating",
      "review_count",
      "is_featured",
      "is_new_arrival",
      "is_best_seller",
      "is_active",
      "is_made_to_order",
      "created_at",
    ];
    const values = [
      lit(p.slug),
      lit(p.name),
      lit(p.description),
      lit(p.shortDescription),
      p.price,
      lit(p.salePrice ?? null),
      lit(p.categorySlug),
      lit(p.subcategorySlug ?? null),
      lit(p.fabric ?? null),
      lit(p.pieces ?? null),
      lit(p.care ?? null),
      textArray(p.tags),
      p.rating,
      p.reviewCount,
      lit(p.isFeatured),
      lit(p.isNewArrival),
      lit(p.isBestSeller),
      "true",
      lit(p.isMadeToOrder === true),
      lit(p.createdAt),
    ];

    out.push(`-- ${p.name}`);
    out.push(
      `insert into products (${columns.join(", ")}) values (${values.join(", ")}) ` +
        `on conflict (slug) do update set ` +
        columns
          .filter((c) => c !== "slug")
          .map((c) => `${c} = excluded.${c}`)
          .join(", ") +
        ";",
    );

    // Images and collection links have no natural key worth upserting on, so
    // they are replaced rather than merged. Same choice seed-supabase makes.
    out.push(
      `delete from product_images where product_id = (select id from products where slug = ${lit(p.slug)});`,
    );
    p.images.forEach((image, index) => {
      out.push(
        `insert into product_images (product_id, url, alt, sort_order, is_primary) values (` +
          `(select id from products where slug = ${lit(p.slug)}), ${lit(image.url)}, ${lit(image.alt)}, ${index}, ${lit(index === 0)});`,
      );
    });

    for (const variant of p.variants) {
      out.push(
        `insert into product_variants (product_id, sku, size, color_name, color_hex, stock) values (` +
          `(select id from products where slug = ${lit(p.slug)}), ${lit(variant.sku)}, ${lit(variant.size)}, ${lit(variant.colorName)}, ${lit(variant.colorHex)}, ${variant.stock}) ` +
          `on conflict (sku) do update set product_id = excluded.product_id, size = excluded.size, color_name = excluded.color_name, color_hex = excluded.color_hex, stock = excluded.stock;`,
      );
    }
    out.push("");
  }

  console.log(out.join(NEWLINE));
} finally {
  await server.close();
}
